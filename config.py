# ===== Настройки бота «Падающая звезда» =====
# Правила звезды (по умолчанию) взяты из индикатора TradingView «Hammer & ShootingStar Candle Detector» (MoriFX), только падающая звезда.
# Меняйте только числа и True/False справа от «=». Остальное не трогайте.

TITLE = "Падающая звезда"   # используется только в тестовом сообщении

# --- Где что искать ---
STAR_TIMEFRAMES = ["4H", "1H"]               # сначала проверяется 4ч, затем 1ч
CONFIRM_TIMEFRAMES = ["15m", "30m"]          # нужны только если CONFIRM_ALERTS = True

# --- Монеты (USDT-перпетуалы OKX) ---
# Бот проверяет не фиксированный список, а только «полезные» монеты: ликвидные и растущие за сутки.
# Звезде нужен рост (свеча на подъёме выше SMA), поэтому падающие и стоящие на месте монеты проверять незачем.
MIN_TURNOVER_USDT = 3_000_000   # суточный оборот не меньше этого (отсеивает редкие, малоликвидные монеты)
ONLY_RISING = True              # True = только монеты, выросшие за последние 24 часа
MIN_24H_CHANGE_PCT = 0.0        # рост за 24 часа не меньше стольки процентов (0 = просто «в плюсе», 3 = только заметный рост)
TOP_COINS = 100                 # не больше стольких монет за проход (первыми идут самые оборотистые); больше = дольше проход
EXCLUDE = []                    # исключения, например ["DOGE-USDT-SWAP"]

# --- Что присылать ---
STAR_ALERT = True           # сообщение сразу после закрытия свечи-звезды
CONFIRM_ALERTS = False      # False = только сообщение о звезде; True = ещё и сообщения о начале падения (15м/30м)
STAR_COOLDOWN_HOURS = 0     # пауза между сообщениями по одной монете и таймфрейму; 0 = сообщать о каждой звезде

# --- Правило звезды ---
STAR_RULE = "morifx"                  # "morifx" = как в индикаторе MoriFX (см. README); "percent" = прежние проценты диапазона (блок ниже)
MORIFX_OPEN_BELOW_PREV_CLOSE = True   # как в индикаторе: звезда открылась не выше закрытия предыдущей свечи (open <= close[1]); False = не проверять

# --- Форма свечи: падающая звезда (доли диапазона свечи; работает только при STAR_RULE = "percent") ---
FALLING_ENABLED = True              # False = падающую звезду не искать
FALLING_UPPER_WICK_MIN = 0.50       # верхняя тень не меньше 50% диапазона
FALLING_BODY_MAX = 0.35             # тело не больше 35% диапазона
FALLING_LOWER_WICK_MAX = 0.15       # нижняя тень не больше 15% диапазона
FALLING_UPPER_TO_BODY = 2.0         # верхняя тень не меньше 2 тел свечи
FALLING_SKIP_AFTER_BIG_GREEN = False  # False = как в индикаторе: предыдущая свеча не важна

# --- Вечерняя звезда (в индикаторе её нет, поэтому по умолчанию выключена) ---
EVENING_ENABLED = False             # True = искать и вечернюю звезду
EVENING_UPPER_WICK_MIN = 0.40       # верхняя тень не меньше 40% диапазона
EVENING_BODY_MAX = 0.30             # тело не больше 30% диапазона
EVENING_LOWER_WICK_MIN = 0.25       # нижняя тень не меньше 25% (так вечерняя отделена от падающей)
EVENING_LOWER_WICK_MAX = 0.55       # нижняя тень не больше 55% диапазона
EVENING_REQUIRE_GREEN = True        # True = перед звездой обязательно большая зелёная свеча
PREV_GREEN_BODY_MULT = 1.0          # «большая» = тело зелёной свечи не меньше среднего тела за 20 свечей × это число
STAR_BODY_VS_PREV_MAX = 0.7         # тело звезды не больше 70% тела зелёной свечи

# --- Размер свечи ---
ATR_PERIOD = 14             # период ATR
MIN_RANGE_ATR = 0           # диапазон свечи не меньше стольких ATR; 0 = не проверять (в индикаторе MoriFX такой проверки нет; прежнее значение 0.5)

# --- Тренд (звезда должна быть на росте) ---
TREND_FILTER = False        # False = тренд не проверять (в индикаторе MoriFX такой проверки нет); True = цена выше растущей SMA
SMA_PERIOD = 20             # период SMA
REQUIRE_RISING_SMA = True   # SMA должна расти (текущее значение выше предыдущего)
MIN_BARS_ABOVE_SMA = 3      # столько свечей подряд (считая звезду) закрылись выше SMA
REQUIRE_LOCAL_HIGH = True   # максимум звезды не ниже максимумов предыдущих N свечей (только при STAR_RULE = "percent"; в правиле MoriFX это условие встроено)
LOCAL_HIGH_LOOKBACK = 10    # это N

# --- RSI (сейчас не проверяется; значение RSI всё равно показывается в сообщении) ---
RSI_FILTER = False          # False = RSI не проверять; True = звезду с RSI ниже RSI_MIN не учитываем
RSI_MIN = 70                # RSI не ниже этого значения
RSI_LOOKBACK = 1            # 1 = RSI проверяется только на самой звезде; 2-3 = достаточно любой из последних N свечей
REQUIRE_DIVERGENCE = False  # True = ещё и медвежья дивергенция (цена на максимуме, RSI ниже прежнего пика)

# --- Прочее для звезды ---
REQUIRE_RED_BODY = False    # True = звезда обязательно красная (закрытие ниже открытия)
MIN_VOLUME_MULT = 0         # 0 = не проверять; 1.5 = объём звезды не меньше 1.5 среднего за 20 свечей

# --- Начало падения (работает, только если CONFIRM_ALERTS = True) ---
CONFIRM_LEVEL = "low"       # "low" = закрытие ниже минимума звезды; "body" = ниже низа тела звезды
REQUIRE_RED_CONFIRM = True  # подтверждающая свеча 15м/30м должна быть красной
MAX_CHASE_RANGES = 1.0      # не слать, если цена уже ушла ниже уровня больше чем на N диапазонов звезды
COIN_COOLDOWN_HOURS = 4     # cooldown финальных сигналов отдельно для 1ч и 4ч одной монеты

# --- Запросы к бирже ---
REQUEST_PAUSE = 8.0         # пауза между запросами к бирже, секунд (при ошибках бот сам ждёт дольше)
