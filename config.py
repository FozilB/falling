# ===== Настройки бота «Падающая и вечерняя звезда» =====
# Один бот ищет оба вида звезды по тем же правилам, что индикатор «Проверка звезды» в TradingView.
# Меняйте только числа и True/False справа от «=». Остальное не трогайте.

TITLE = "Падающая и вечерняя звезда"   # используется только в тестовом сообщении

# --- Где что искать ---
STAR_TIMEFRAMES = ["1H"]               # сама звезда ищется только на 1ч (чтобы добавить 4ч: ["1H", "4H"])
CONFIRM_TIMEFRAMES = ["30m"]          # начало падения ищется на свечах 30м (допустимо 15m и 30m; свечи 30м собираются из 15м, лишних запросов нет)

# --- Монеты ---
TOP_COINS = 75      # сколько самых оборотистых USDT-перпетуалов OKX смотреть (каждые 25 монет = около 3,5 минуты на таймфрейм)
EXCLUDE = []        # исключения, например ["DOGE-USDT-SWAP"]

# --- Падающая звезда (доли диапазона свечи, от минимума до максимума) ---
FALLING_ENABLED = True              # False = падающую звезду не искать
FALLING_UPPER_WICK_MIN = 0.60       # верхняя тень больше 60% диапазона
FALLING_BODY_MAX = 0.20             # тело меньше 20% диапазона
FALLING_LOWER_WICK_MAX = 0.15       # нижняя тень меньше 15% диапазона
FALLING_SKIP_AFTER_BIG_GREEN = False  # False = как в индикаторе: предыдущая свеча не важна

# --- Вечерняя звезда ---
EVENING_ENABLED = True              # False = вечернюю звезду не искать
EVENING_UPPER_WICK_MIN = 0.40       # верхняя тень больше 40% диапазона
EVENING_BODY_MAX = 0.30             # тело меньше 30% диапазона
EVENING_LOWER_WICK_MIN = 0.25       # нижняя тень не меньше 25% (так вечерняя отделена от падающей)
EVENING_LOWER_WICK_MAX = 0.55       # нижняя тень меньше 55% диапазона
EVENING_REQUIRE_GREEN = True        # True = перед звездой обязательно большая зелёная свеча
PREV_GREEN_BODY_MULT = 1.0          # «большая» = тело зелёной свечи не меньше среднего тела за 20 свечей × это число
STAR_BODY_VS_PREV_MAX = 0.7         # тело звезды не больше 70% тела зелёной свечи

# --- Общее для обоих видов ---
LOCAL_HIGH_LOOKBACK = 10    # максимум звезды выше максимумов предыдущих N свечей
REQUIRE_RED_BODY = False    # True = звезда обязательно красная (закрытие ниже открытия)
MIN_VOLUME_MULT = 0         # 0 = не проверять; 1.5 = объём звезды не меньше 1.5 среднего за 20 свечей

# --- Сообщение о найденной звезде ---
STAR_ALERT = True           # True = писать сразу, когда звезда найдена (до падения); False = только когда падение началось

# --- Начало падения (подтверждение) ---
CONFIRM_LEVEL = "low"       # "low" = закрытие ниже минимума звезды; "body" = ниже низа тела звезды
REQUIRE_RED_CONFIRM = True  # подтверждающая свеча 15м/30м должна быть красной
MAX_CHASE_RANGES = 1.0      # не слать, если цена уже ушла ниже уровня больше чем на N диапазонов звезды
COIN_COOLDOWN_HOURS = 4     # по одной монете не чаще одного сообщения за N часов (на оба вида вместе)

# --- Запросы к бирже ---
REQUEST_PAUSE = 8.0         # пауза между запросами к бирже, секунд (при ошибках бот сам ждёт дольше)
